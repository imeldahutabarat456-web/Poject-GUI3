    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
     int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih data yang akan dihapus!");
        return;
    }

    String nim = jTable1.getValueAt(selectedRow, 1).toString();
    
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Apakah Anda yakin ingin menghapus data dengan NIM: " + nim + "?", 
            "Konfirmasi Hapus", 
            javax.swing.JOptionPane.YES_NO_OPTION);
            
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        try {
            studentController.delete(this,nim);
            javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil dihapus.");
            loadData(); // Panggil ulang untuk menyegarkan tabel
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnHapusActionPerformed

