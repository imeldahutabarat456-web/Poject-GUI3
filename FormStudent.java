    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {                                     
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0) {
            // Urutan Kolom sesuai dengan susunan loadData():
            // 0 = ID (NIK), 1 = Nama, 2 = NIM, 3 = Program Studi
        txtIdCard.setText(jTable1.getValueAt(selectedRow, 0).toString());
        txtNim.setText(jTable1.getValueAt(selectedRow, 1).toString());
        txtNama.setText(jTable1.getValueAt(selectedRow, 2).toString());
        txtProdi.setText(jTable1.getValueAt(selectedRow, 3).toString());
        
        txtNim.setEditable(false);
        txtIdCard.setEditable(false);
    }
        }
                                                                

    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {                                        
        String keyword = javax.swing.JOptionPane.showInputDialog(this,
                "Masukkan Nama atau NIM Mahasiswa:", 
                "Pencarian Mahasiswa",
                javax.swing.JOptionPane.QUESTION_MESSAGE);
        
        if (keyword != null && !keyword.trim().isEmpty()) {
            java.util.List<model.Student> list = studentController.searchStudents(keyword.trim());
            tableModel.setRowCount(0); 
            for (model.Student s : list) {
                tableModel.addRow(new Object[]{
                    s.getIdCard(),
                    s.getNim(),
                    s.getNama(),
                    s.getProdi()
                });
            }
        } else if (keyword != null) {
            loadData(); 
        }
    }                                       

    private final StudentController studentController = new StudentController(); 
    private javax.swing.table.DefaultTableModel tableModel;
    
    private int currentPage = 1;
    private final int limit = 5;

    private void loadData() {
        java.util.List<model.Student> list = studentController.getAllStudents();
        tableModel.setRowCount(0); 
        for (model.Student s : list) {
            tableModel.addRow(new Object[]{
                s.getIdCard(),
                s.getNim(),
                s.getNama(),
                s.getProdi()
            });
        }
        btnPrev.setEnabled(currentPage > 1); // Mati di halaman pertama
        btnNext.setEnabled(list.size() == limit); // Mati jika sisa baris data sudah habis
    }

    private void clearFields() {
        txtIdCard.setText("");
        txtNim.setText("");
        txtNama.setText(""); 
        txtProdi.setText("");
        txtNim.setEditable(true); 
        txtIdCard.setEditable(true); 
    }
