    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
    String idCard = txtIdCard.getText().trim();
    if (!idCard.isEmpty()) {
    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
        "Yakin ingin menghapus dosen ini?", "Konfirmasi Hapus", 
        javax.swing.JOptionPane.YES_NO_OPTION);
        
    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        if (lecturerController.delete(this, idCard)) {
            clearFields();
            loadData();
        }
    }
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu!");
}
    }//GEN-LAST:event_btnHapusActionPerformed

