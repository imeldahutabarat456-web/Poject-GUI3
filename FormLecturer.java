    private void tableLecturerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableLecturerMouseClicked
     int selectedRow = tableLecturer.getSelectedRow();
     if (selectedRow >= 0) {
         
    txtNama.setText(tableModel.getValueAt(selectedRow, 0).toString());
    txtIdCard.setText(tableModel.getValueAt(selectedRow, 1).toString());
    txtNind.setText(tableModel.getValueAt(selectedRow, 2).toString());
    txtExpertise.setText(tableModel.getValueAt(selectedRow, 3).toString());
    
    txtIdCard.setEditable(false); // Kunci ID Card biar gak diedit sembarangan
}
    }//GEN-LAST:event_tableLecturerMouseClicked

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
               
    String idCard = txtIdCard.getText().trim();
    String nama = txtNama.getText().trim();
    String nidn = txtNind.getText().trim();
    String expertise = txtExpertise.getText().trim();
    
    if (lecturerController.update(this, idCard, nama, nidn, expertise)) {
        clearFields();
        loadData(); // Refresh tabel setelah diubah
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
    String keyword = javax.swing.JOptionPane.showInputDialog(this,
            "Masukkan Nama atau ID Card Dosen:", 
            "Pencarian Dosen",
            javax.swing.JOptionPane.QUESTION_MESSAGE);
    
    if (keyword != null && !keyword.trim().isEmpty()) {
        java.util.List<model.Lecturer> list = lecturerController.searchLecturers(keyword.trim());
        tableModel.setRowCount(0); 
        for (model.Lecturer l : list) {
            tableModel.addRow(new Object[]{
                l.getNama(),
                l.getIdCard(),
                l.getNidn(),
                l.getExpertise()
            });
        }
    } else if (keyword != null) {
        loadData(); // Jika pencarian dikosongkan, tampilkan semua data lagi
    
    }//GEN-LAST:event_btnCariActionPerformed
    }
    private final LecturerController lecturerController = new LecturerController(); 
    private javax.swing.table.DefaultTableModel tableModel;

    private void initTable() {
        tableModel = (javax.swing.table.DefaultTableModel) tableLecturer.getModel();
    }

    private void loadData() {
        java.util.List<model.Lecturer> list = lecturerController.getAllLecturers();
        tableModel.setRowCount(0); 
        for (model.Lecturer l : list) {
            tableModel.addRow(new Object[]{
                l.getNama(),
                l.getIdCard(),
                l.getNidn(),
                l.getExpertise()
            });
        }
    }

    private void clearFields() {
        txtIdCard.setText("");
        txtNama.setText("");
        txtNind.setText(""); 
        txtExpertise.setText("");
        txtIdCard.setEditable(true); 
    }
