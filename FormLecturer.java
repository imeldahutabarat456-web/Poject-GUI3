    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        String idCard = txtIdCard.getText().trim();
        String nama = txtNama.getText().trim();
        String nidn = txtNind.getText().trim();
        String expertise = txtExpertise.getText().trim();
        
        if (lecturerController.insert(this, idCard, nama, nidn, expertise)) {
            clearFields(); // Bersihkan form setelah sukses
            loadData();    // Refresh isi tabel
}
    }//GEN-LAST:event_btnSimpanActionPerformed

